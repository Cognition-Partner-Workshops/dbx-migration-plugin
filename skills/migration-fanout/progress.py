import argparse
import json
import re
from pathlib import Path


_HEADER = "<!-- generated by skills/migration-fanout/progress.py from waves/*.result.json; do not edit -->"
_TABLE_HEADER = "| wave | batch | unit | status | recon_verdict | pr_url | recon_cost |"
_TABLE_DIVIDER = "|---|---|---|---|---|---|---|"
_WAVE_NAME = re.compile(r"wave-(\d+)\.result\.json$")
_RESULT_SUFFIX = ".result.json"


def _text(value) -> str:
    return "" if value is None else str(value)


def _bool(value) -> str:
    if isinstance(value, bool):
        return str(value).lower()
    return _text(value)


def _wave_key(value):
    return (0, value) if isinstance(value, int) and not isinstance(value, bool) else (1, _text(value))


def _wave(result: dict, path: Path):
    wave = result.get("wave")
    if wave is not None:
        return wave
    match = _WAVE_NAME.fullmatch(path.name)
    return int(match.group(1)) if match else ""


def _manifest_units(path: Path) -> dict:
    manifest_path = path.with_name(path.name[:-len(_RESULT_SUFFIX)] + ".json")
    if not manifest_path.exists():
        return {}
    try:
        manifest = json.loads(manifest_path.read_text())
    except (OSError, ValueError):
        return {}
    if not isinstance(manifest, dict) or not isinstance(manifest.get("batches"), list):
        return {}
    return {
        batch.get("id"): batch["units"]
        for batch in manifest["batches"]
        if isinstance(batch, dict) and isinstance(batch.get("units"), list)
    }


def render_progress(mig: Path) -> str:
    waves = mig / "waves"
    results = []
    for path in sorted(waves.glob("*.result.json")):
        try:
            result = json.loads(path.read_text())
        except ValueError:
            raise ValueError(f"{path}: not a JSON object") from None
        if not isinstance(result, dict):
            raise ValueError(f"{path}: not a JSON object")
        results.append((result, path))

    rows = []
    for result, path in results:
        wave = _wave(result, path)
        manifest_units = _manifest_units(path)
        for batch in result.get("batches", []):
            if not isinstance(batch, dict):
                continue
            cost = batch.get("recon_cost")
            cost_text = json.dumps(cost, sort_keys=True, separators=(",", ":")) \
                if isinstance(cost, dict) else ""
            units = batch.get("units")
            if not isinstance(units, list):
                units = manifest_units.get(batch.get("id"), [])
            for unit in units:
                rows.append((
                    wave,
                    _text(batch.get("id")),
                    _text(unit),
                    _text(batch.get("status")),
                    _text(batch.get("recon_verdict")),
                    _text(batch.get("pr_url")),
                    cost_text,
                ))
    rows.sort(key=lambda row: (_wave_key(row[0]), row[1], row[2]))

    lines = [_HEADER, _TABLE_HEADER, _TABLE_DIVIDER]
    lines.extend("| " + " | ".join(_text(value) for value in row) + " |" for row in rows)
    for result, path in sorted(results, key=lambda item: _wave_key(_wave(*item))):
        wave = _wave(result, path)
        breaker = result.get("breaker_tripped_on") or "-"
        lines.append(
            f"wave {wave}: closed={_bool(result.get('closed'))}, "
            f"auto_merge={_bool(result.get('auto_merge'))}, breaker_tripped_on={breaker}"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("migration_dir", type=Path)
    args = parser.parse_args(argv)
    output = args.migration_dir / "05_progress.md"
    output.write_text(render_progress(args.migration_dir))
    print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
